"""Advisory checks for formulaic, machine-like phrasing in Indonesian prose.

These checks are review signals, not authorship detection. They flag reusable
phrases and unusually uniform sentence lengths so a writer can revise them;
they never assert that text was generated by a model and never edit the text.
"""

import re
from dataclasses import dataclass

# Rewritten from common editorial guidance rather than copied from any single
# source. Phrases are deliberately specific: ordinary academic vocabulary such
# as "signifikan" or "literatur" is not penalised on its own.
FORMULAIC_PHRASES: tuple[tuple[str, str], ...] = (
    (r"dalam dunia yang (?:semakin|terus|makin)", "generic opener"),
    (r"di era (?:digital|modern|globalisasi|informasi)", "generic opener"),
    (r"seiring dengan (?:perkembangan|kemajuan|derasnya)", "generic opener"),
    (r"(?:penting|perlu) untuk dicatat", "filler"),
    (r"cukup penting untuk (?:ditekankan|diperhatikan)", "filler"),
    (r"tidak dapat dipungkiri", "filler"),
    (r"tidak bisa diabaikan", "filler"),
    (r"perlu diingat bahwa", "filler"),
    (r"memainkan peran (?:yang )?(?:penting|krusial|vital|signifikan)", "generic claim"),
    (r"(?:memberikan|memberi) kontribusi (?:yang )?(?:besar|penting|signifikan)", "generic claim"),
    (r"berdampak (?:yang )?(?:besar|signifikan|positif) terhadap", "generic claim"),
    (r"memiliki implikasi (?:yang )?penting", "generic claim"),
    (r"(?:sangat|amat) (?:penting|krusial|esensial)", "generic claim"),
    (r"secara (?:komprehensif|keseluruhan|umum),?\s+(?:dapat|bisa)\s+(?:disimpulkan|dikatakan)", "wrap-up"),
    (r"dengan demikian,?\s+(?:dapat|bisa)\s+(?:dikatakan|disimpulkan)", "wrap-up"),
    (r"sebagai (?:sebuah )?(?:model bahasa|AI|kecerdasan buatan),?\s+(?:saya|kami)", "assistant residue"),
    (r"berikut (?:adalah|ini adalah)", "assistant residue"),
    (r"semoga (?:membantu|bermanfaat)", "assistant residue"),
)

_COMPILED_PHRASES = tuple(
    (re.compile(pattern, re.IGNORECASE), category)
    for pattern, category in FORMULAIC_PHRASES
)
_MARKDOWN_BOLD_RE = re.compile(r"\*\*[^*\n]+\*\*")
_SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?])\s+")
_WORD_RE = re.compile(r"[^\W\d_]+(?:['’-][^\W\d_]+)*", re.UNICODE)

# Six equal-length sentences are a strong enough rhythm signal; below that the
# coefficient of variation is too noisy to act on.
_MIN_SENTENCES_FOR_RHYTHM = 6
_UNIFORM_CV = 0.18


@dataclass(frozen=True)
class FormulaicHit:
    phrase: str
    category: str

    def to_dict(self) -> dict[str, str]:
        return {"phrase": self.phrase, "category": self.category}


def detect_formulaic_phrases(prose: str) -> list[FormulaicHit]:
    """Find reviewable formulaic phrases in already-cleaned prose."""

    hits: list[FormulaicHit] = []
    for pattern, category in _COMPILED_PHRASES:
        for match in pattern.finditer(prose):
            hits.append(FormulaicHit(match.group(0).strip(), category))
    for match in _MARKDOWN_BOLD_RE.finditer(prose):
        hits.append(FormulaicHit(match.group(0), "markdown residue"))
    return hits


def sentence_length_cv(prose: str) -> float:
    """Coefficient of variation of sentence word counts; 0.0 means all equal."""

    counts = [
        len(_WORD_RE.findall(sentence))
        for sentence in _SENTENCE_SPLIT_RE.split(prose)
        if len(_WORD_RE.findall(sentence)) > 0
    ]
    if len(counts) < _MIN_SENTENCES_FOR_RHYTHM:
        return 1.0
    mean = sum(counts) / len(counts)
    if mean == 0:
        return 1.0
    variance = sum((count - mean) ** 2 for count in counts) / len(counts)
    return (variance**0.5) / mean


def is_uniform_rhythm(prose: str) -> bool:
    return sentence_length_cv(prose) < _UNIFORM_CV


